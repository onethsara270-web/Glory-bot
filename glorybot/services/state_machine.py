from glorybot.database.models import OrderStatus as S

ALLOWED: dict[S, set[S]] = {
    S.DRAFT: {S.PENDING_PAYMENT, S.PENDING_ADMIN_APPROVAL, S.CANCELLED},
    S.PENDING_PAYMENT: {S.PENDING_ADMIN_APPROVAL, S.CANCELLED},
    S.PENDING_ADMIN_APPROVAL: {S.APPROVED, S.REJECTED, S.CANCELLED},
    S.APPROVED: {S.PROCESSING, S.FAILED},
    S.PROCESSING: {S.SUBMITTED_TO_PROVIDER, S.FAILED, S.REQUIRES_RECONCILIATION},
    S.SUBMITTED_TO_PROVIDER: {S.IN_PROGRESS, S.COMPLETED, S.FAILED, S.REQUIRES_RECONCILIATION, S.REFUNDED},
    S.IN_PROGRESS: {S.COMPLETED, S.FAILED, S.REQUIRES_RECONCILIATION, S.REFUNDED},
    S.REQUIRES_RECONCILIATION: {S.SUBMITTED_TO_PROVIDER, S.IN_PROGRESS, S.COMPLETED, S.FAILED},
    S.FAILED: {S.REFUNDED},
    S.REJECTED: {S.REFUNDED},
    S.CANCELLED: {S.REFUNDED},
    S.COMPLETED: {S.REFUNDED},
    S.REFUNDED: set(),
}


class InvalidTransition(Exception):
    pass


def check_transition(old: S, new: S) -> None:
    if new not in ALLOWED[old]:
        raise InvalidTransition(f"{old.value} -> {new.value} is not allowed")
